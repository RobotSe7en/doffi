/** Explicit, read-only capture of synthetic, already-public Office inputs.
 * It never writes an archived acceptance baseline or authenticates an account. */
import { parseArgs } from 'node:util';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from '@playwright/test';

const { values } = parseArgs({ options: {
  'source-commit': { type: 'string' }, input: { type: 'string', multiple: true }, out: { type: 'string', default: '.cache/excel-web-probes' },
} });
if (!values['source-commit'] || !/^[a-f0-9]{40}$/.test(values['source-commit'])) throw Error('Supply the immutable public source commit SHA.');
const supported = ['recalculation', 'name-semantics', 'qualified-context', 'relative-bounds'];
const inputs = values.input ?? ['recalculation', 'name-semantics'];
if (!inputs.length || new Set(inputs).size !== inputs.length || inputs.some(input => !supported.includes(input))) throw Error('Choose distinct declared synthetic inputs.');
const directory = resolve(values.out); await mkdir(directory, { recursive: true });
const browser = await chromium.launch({ headless: true });
try {
  for (const name of inputs) {
    const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 1000 } });
    try {
      const source = `https://raw.githubusercontent.com/RobotSe7en/doffi/${values['source-commit']}/docs/evidence/excel-web-inputs/${name}.xlsx`;
      const remote = await context.request.get(source, { timeout: 20_000 });
      const sha256 = createHash('sha256').update(await remote.body()).digest('hex');
      const input = JSON.parse(await readFile(new URL(`../docs/evidence/excel-web-inputs/${name}.xlsx.json`, import.meta.url), 'utf8'));
      if (remote.status() !== 200 || sha256 !== input.sha256) throw Error('The public input does not match the independently generated bytes.');
      const page = await context.newPage(), versions = new Set();
      page.on('response', response => { if (response.url().includes('xlviewerinternal.aspx')) void response.allHeaders().then(headers => {
        const version = headers['x-officeversion']; if (version && /^\d+(\.\d+){2,}$/.test(version)) versions.add(version);
      }).catch(() => {}); });
      await page.goto('https://view.officeapps.live.com/op/view.aspx?src=' + encodeURIComponent(source), { waitUntil: 'domcontentloaded', timeout: 20_000 });
      await page.frameLocator('iframe').getByRole('combobox', { name: /Name Box/ }).waitFor({ state: 'visible', timeout: 30_000 });
      const frame = page.frames().find(value => value.url().includes('xlviewerinternal'));
      if (!frame) throw Error('The authorized public Excel view did not open.');
      const states = [];
      for (const sheet of [...new Set(input.cells.map(cell => cell.sheet))]) {
        if (states.length) await frame.getByText(sheet, { exact: true }).last().click({ timeout: 5000 });
        await page.waitForTimeout(2500);
        const repair = await frame.getByText(/WORKBOOK REPAIRED/i).count() > 0;
        const screenshot = `${name}-${sheet}.png`;
        await page.screenshot({ path: resolve(directory, screenshot) });
        states.push({ sheet, repair, screenshot });
      }
      const report = { status: 'capture-only', scope: 'Synthetic public read-only Excel web view; rendered values require independent inspection. No editing, desktop, WPS or fixed-font visual acceptance.',
        source, sourceCommit: values['source-commit'], sourceSha256: sha256, observedAt: new Date().toISOString(), officeVersions: [...versions], states };
      await writeFile(resolve(directory, `${name}.json`), JSON.stringify(report, null, 2) + '\n');
      process.stdout.write(JSON.stringify({ input: name, versions: [...versions], repairs: states.filter(state => state.repair).map(state => state.sheet), output: directory }) + '\n');
    } finally { await context.close(); }
  }
} finally { await browser.close(); }
